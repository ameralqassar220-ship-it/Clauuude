"""Builds the audience-specific versions of the 'made to measure' reel for Meta ads.

Each version = its own spoken hook (audio/hook-<id>.mp3) + the shared narration from precision.mp3
(from "You send us your measurements…"), with audience-specific kicker, hook photos, captions and CTA line.
Writes audio/aud-<id>.mp3 and reels/aud-<id>.js; render with: node render.js aud-<id>
"""
import json, re, subprocess, os
HERE = os.path.dirname(os.path.abspath(__file__)); AUD = os.path.join(HERE, '..', 'audio')
BODY_FROM = 3.40      # where the shared narration starts in precision.mp3
GAP = 0.35            # breath between hook and narration
hooks = json.load(open(os.path.join(AUD, 'hooks.json')))
hooks['designers']['split'] = 1.62   # manual: the pause after "interior designer,"

A = {
  'designers':    dict(kicker='For Interior Designers', tag='For interior designers',
                       a='If you’re an interior designer,', b='your client expects every door to fit perfectly!', ahl={3: 'hl', 4: 'hl'}, bhl={6: 'hs', 7: 'hs'},
                       imgs=['gold-mesh-fabric-glass-wardrobe-doors-dressing-room.jpg', 'dark-walk-in-closet-glass-doors-lit-shelves.jpg'],
                       ship='Send your client’s measurements on WhatsApp'),
  'joinery':      dict(kicker='For Joinery Workshops', tag='For joinery workshop owners',
                       a='If you own a joinery workshop,', b='you can’t afford doors that don’t fit!', ahl={4: 'hl', 5: 'hl'}, bhl={5: 'hs', 6: 'hs'},
                       imgs=['air-hinge-aluminium-profile-corner.jpg', '175-degree-cabinet-hinge.jpg'],
                       ship='Daily or weekly supply for your workshop'),
  'architects':   dict(kicker='For Architects', tag='For architects',
                       a='If you’re an architect,', b='your design deserves doors that fit exactly as drawn!', ahl={3: 'hl'}, bhl={6: 'hs', 7: 'hs', 8: 'hs'},
                       imgs=['doc-draw-1.jpg', 'grey-fluted-glass-walk-in-closet-black-frame.jpg'],
                       ship='Send your door schedule on WhatsApp'),
  'developers':   dict(kicker='For Real Estate Developers', tag='For real estate developers',
                       a='If you’re a real estate developer,', b='every unit needs doors that fit, on time!', ahl={3: 'hl', 4: 'hl', 5: 'hl'}, bhl={1: 'hs', 6: 'hs', 7: 'hs'},
                       imgs=['walk-in-closet-aluminium-glass-doors-uae.jpg', 'aluminium-glass-wardrobe-doors-bedroom.jpg'],
                       ship='Project supply for every unit, on time'),
  'construction': dict(kicker='For Construction Companies', tag='For construction companies',
                       a='If you run a construction company,', b='every site needs doors that fit the first time!', ahl={4: 'hl', 5: 'hl'}, bhl={1: 'hs', 6: 'hs', 7: 'hs', 8: 'hs'},
                       imgs=['razan-uae-team-warehouse.jpg', 'fluted-glass-wardrobe-doors-uae.jpg'],
                       ship='Site delivery across the UAE'),
}

# shared body (times are precision.mp3 seconds) — taken from precision.js
base = open(os.path.join(HERE, 'precision.js')).read()
scenes_src = base[base.index('scenes: [') + len('scenes: ['):base.index('  ],\n  caps:')]
caps_src = base[base.index('caps: [') + len('caps: ['):base.rindex('  ],')]
body_scenes = scenes_src.split('\n')[2:]          # drop hook2 line (first line is blank)
body_scenes = '\n'.join(body_scenes)
body_caps = '\n'.join(caps_src.split('\n')[3:])  # drop blank + the two hook caption lines

for k, o in A.items():
    h = hooks[k]; hook_len = h['dur'] + 0.11   # clip = speech -0.03 … +0.08
    shift = hook_len + GAP - BODY_FROM
    out_mp3 = os.path.join(AUD, f'aud-{k}.mp3')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', os.path.join(AUD, f'hook-{k}.mp3'),
                    '-f', 'lavfi', '-t', str(GAP), '-i', 'anullsrc=r=44100:cl=mono',
                    '-ss', str(BODY_FROM), '-i', os.path.join(AUD, 'precision.mp3'),
                    '-filter_complex', '[0:a]aresample=44100,aformat=channel_layouts=mono[h];[2:a]aresample=44100,aformat=channel_layouts=mono[b];[h][1:a][b]concat=n=3:v=0:a=1',
                    '-c:a', 'libmp3lame', '-q:a', '2', out_mp3], check=True)
    dur = float(subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', out_mp3], capture_output=True, text=True).stdout)
    sh = lambda m: f"{float(m.group(1)) + shift:.2f}"
    sc = re.sub(r"at: ([0-9.]+), (img|imgs|ship)", lambda m: f"at: {float(m.group(1)) + shift:.2f}, {m.group(2)}", body_scenes)
    sc = re.sub(r"ship: '[^']*'", "ship: " + json.dumps(o['ship'], ensure_ascii=False), sc)
    cp = re.sub(r"\[\[?([0-9.]+), ([0-9.]+), '", lambda m: m.group(0).replace(m.group(1), f"{float(m.group(1)) + shift:.2f}", 1).replace(m.group(2), f"{float(m.group(2)) + shift:.2f}", 1), body_caps)
    a0, sp = 0.03, h['split']
    js = f"""// AUTO-GENERATED by make_audience_reels.py — audience: {k}. Edit the generator, not this file.
window.REEL = {{
  kicker: {json.dumps(o['kicker'], ensure_ascii=False)}, audio: 'aud-{k}.mp3', offset: 0.3, duration: {dur + 2.6:.1f},
  spoken: {{ 'razanuae.com!': 17, 'air-hinge,': 8 }},
  scenes: [
    {{ type: 'hook2', at: 0, imgs: {json.dumps(o['imgs'])}, tag: {json.dumps(o['tag'], ensure_ascii=False)} }},
{sc}
  ],
  caps: [
    {{ hl: {json.dumps({str(i): v for i, v in o['ahl'].items()})}, segs: [[{a0:.2f}, {sp - .06:.2f}, {json.dumps(o['a'], ensure_ascii=False)}]] }},
    {{ hl: {json.dumps({str(i): v for i, v in o['bhl'].items()})}, segs: [[{sp + .02:.2f}, {h['dur']:.2f}, {json.dumps(o['b'], ensure_ascii=False)}]] }},
{cp}
  ],
}};
"""
    open(os.path.join(HERE, f'aud-{k}.js'), 'w').write(js)
    print(k, f'hook {hook_len:.2f}s  shift {shift:+.2f}s  total audio {dur:.2f}s')
